/** Fills a translated sentence where %s stands for a name, number or product. */
export function fill(template: string, value: string): string {
  return template.replace("%s", value);
}

/** Fills a sentence holding two %s placeholders, in order. */
export function fill2(template: string, first: string, second: string): string {
  const parts = template.split("%s");
  return `${parts[0] ?? ""}${first}${parts[1] ?? ""}${second}${parts.slice(2).join("%s")}`;
}

