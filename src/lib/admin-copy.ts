export const adminDictionaries: Record<
  Language,
  Record<AdminCopyKey, string>
> = { ar, en };

export function isAdminCopyKey(value: unknown): value is AdminCopyKey {
  return typeof value === "string" && value in ar;
}

/** Looks up a key and fills {placeholders}; unknown keys (legacy server text) pass through. */
export function adminText(
  language: Language,
  key: AdminCopyKey | string,
  vars?: Record<string, string | number>,
): string {
  let text = isAdminCopyKey(key) ? adminDictionaries[language][key] : key;
  if (vars)
    for (const [name, value] of Object.entries(vars))
      text = text.replaceAll(`{${name}}`, String(value));
  return text;
}

/** Human-readable label for an audit-log action such as "product.save". */
export function actionLabel(language: Language, action: string): string {
  const key = `act_${action.replace(/[.-]/g, "_")}`;
  if (isAdminCopyKey(key)) return adminDictionaries[language][key];
  // Unknown event keys read as words rather than code ("ai.foo-bar" → "Ai foo bar").
  const words = action.replace(/[._-]+/g, " ").trim();
  return words.charAt(0).toUpperCase() + words.slice(1);
}
